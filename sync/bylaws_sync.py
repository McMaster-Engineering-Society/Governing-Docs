#!/usr/bin/env python3
"""
Bylaws sync: Google Docs -> LaTeX (one way).

    python3 sync/bylaws_sync.py pull            # download docs, rewrite .tex files
    python3 sync/bylaws_sync.py seed [files...] # one-time: .tex -> .docx for upload

Requires Python 3.11+ and pandoc on the PATH. No third-party Python packages.
"""
import argparse
import re
import shutil
import subprocess
import sys
import tomllib
import urllib.error
import urllib.request
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "sync" / "docs.toml"
FILTERS = ROOT / "sync" / "filters"

HEADER = (
    "% AUTO-GENERATED from Google Doc https://docs.google.com/document/d/{id}/edit\n"
    "% Do not edit this file by hand: it is overwritten on every sync.\n"
    "% Make changes in the Google Doc instead.\n\n"
)


def load_manifest():
    with open(MANIFEST, "rb") as f:
        return tomllib.load(f).get("doc", [])


def is_placeholder(doc_id):
    return not doc_id or doc_id.strip().upper().startswith("TODO")


def download_docx(doc_id, dest):
    url = f"https://docs.google.com/document/d/{doc_id}/export?format=docx"
    req = urllib.request.Request(url, headers={"User-Agent": "bylaws-sync"})
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            data = resp.read()
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"HTTP {e.code} fetching doc (check the id and sharing settings)")
    except urllib.error.URLError as e:
        raise RuntimeError(f"could not reach Google Docs: {e.reason}")
    # A .docx is a zip file. If we got HTML back, it is Google's sign-in page.
    if not data.startswith(b"PK"):
        raise RuntimeError(
            'Google returned a web page instead of the document. Set sharing to '
            '"Anyone with the link can view".'
        )
    dest.write_bytes(data)


def run_pandoc(args, stdin=None):
    exe = shutil.which("pandoc")
    if not exe:
        raise SystemExit(
            "pandoc was not found on your PATH.\n"
            "Install it (Windows: winget install --source winget --exact --id JohnMacFarlane.Pandoc),\n"
            "then CLOSE AND REOPEN your terminal and try again."
        )
    # Force UTF-8: Windows would otherwise use cp1252 and mangle curly quotes/dashes.
    result = subprocess.run([exe, *args], capture_output=True, text=True, encoding="utf-8",
                            cwd=ROOT, input=stdin)
    if result.stderr.strip():
        print(result.stderr.strip(), file=sys.stderr)
    if result.returncode != 0:
        raise RuntimeError(f"pandoc failed (exit {result.returncode})")
    return result.stdout


# Put \label directly under its heading (no blank line), as in the existing files.
HEADING_LABEL = re.compile(
    r"(\\(?:(?:sub){0,2}section|(?:sub)?paragraph)\{[^\n]*\})\n\n(\\label\{[^}\n]*\})"
)


def docx_to_tex(docx_path):
    tex = run_pandoc([
        "-f", "docx",
        "-t", "latex-smart",        # keep curly quotes/dashes as real Unicode (XeLaTeX handles it)
        "--track-changes=reject",   # pending suggestions are NOT published
        "--wrap=none",              # one line per paragraph: clean git diffs
        "--top-level-division=section",
        "--lua-filter", str(FILTERS / "docs-to-latex.lua"),
        str(docx_path),
    ])
    return HEADING_LABEL.sub(r"\1\n\2", tex).strip() + "\n"


def cmd_pull(_args):
    docs = load_manifest()
    changed, errors, skipped = [], [], []
    with tempfile.TemporaryDirectory() as tmp:
        for entry in docs:
            file, doc_id = entry["file"], entry.get("id", "")
            if is_placeholder(doc_id):
                skipped.append(file)
                continue
            try:
                docx = Path(tmp) / "doc.docx"
                download_docx(doc_id, docx)
                body = docx_to_tex(docx)
                if "@@" in body:
                    raise RuntimeError("doc contains a malformed placeholder ('@@' found in the output); "
                                       "fix the {{input:...}} / {{ref:...}} lines in the doc")
                new_text = HEADER.format(id=doc_id) + body
                out = ROOT / file
                if out.exists() and out.read_text(encoding="utf-8") == new_text:
                    print(f"unchanged  {file}")
                    continue
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(new_text, encoding="utf-8", newline="\n")
                changed.append(file)
                print(f"UPDATED    {file}")
            except Exception as e:  # keep going so one bad doc doesn't hide the rest
                errors.append((file, str(e)))
                print(f"ERROR      {file}: {e}", file=sys.stderr)
    for f in skipped:
        print(f"skipped    {f} (no doc id yet)")
    print(f"\n{len(changed)} updated, {len(errors)} errors, {len(skipped)} skipped")
    return 1 if errors else 0


def cmd_seed(args):
    out_dir = ROOT / "sync" / "seed_output"
    out_dir.mkdir(exist_ok=True)
    files = args.files or [d["file"] for d in load_manifest()]
    failed = []
    for file in files:
        src = Path(file)
        if not src.is_absolute():
            src = ROOT / src
        if not src.exists():
            print(f"missing    {file}", file=sys.stderr)
            failed.append(file)
            continue
        dest = out_dir / (src.stem + ".docx")
        # pandoc's LaTeX reader silently discards \nameref and \pageref, and it
        # inlines \input files. Protect both as plain-text markers that
        # tex-to-docx.lua turns into {{nameref:..}} / {{input:..}}.
        text = src.read_text(encoding="utf-8")
        text = re.sub(r"\\(nameref|pageref)\s*\{([^}]*)\}", r"@@\1:\2@@", text)
        # each \input goes in its own paragraph (consecutive lines would otherwise merge)
        text = re.sub(r"\\(input)\s*\{([^}]*)\}", r"\n\n@@\1:\2@@\n\n", text)
        try:
            try:
                dest.unlink(missing_ok=True)   # Windows refuses if the old copy is open elsewhere
            except PermissionError:
                raise RuntimeError(f"{dest.name} is open in another program (Word? File Explorer preview?). "
                                   "Close it and run seed again.")
            run_pandoc([
                "-f", "latex",
                "-t", "docx",
                "--lua-filter", str(FILTERS / "tex-to-docx.lua"),
                "-o", str(dest),
            ], stdin=text)
            print(f"wrote      {dest.relative_to(ROOT)}")
        except RuntimeError as e:
            print(f"FAILED     {file}: {e}", file=sys.stderr)
            failed.append(file)
    if failed:
        print(f"\n{len(failed)} file(s) failed (see messages above):", file=sys.stderr)
        for f in failed:
            print(f"  - {f}", file=sys.stderr)
    print("\nUpload the .docx files to Google Drive, right-click > Open with > Google Docs,")
    print("then copy each doc's id into sync/docs.toml.")
    return 1 if failed else 0


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)
    sub.add_parser("pull", help="download Google Docs and regenerate .tex files").set_defaults(func=cmd_pull)
    s = sub.add_parser("seed", help="convert existing .tex files to .docx for first upload")
    s.add_argument("files", nargs="*", help="defaults to every file in docs.toml")
    s.set_defaults(func=cmd_seed)
    args = p.parse_args()
    sys.exit(args.func(args))


if __name__ == "__main__":
    main()
